def write_png(path: Path, width: int, height: int, pixels) -> None:
    """RGBA8 の PNG を標準ライブラリだけで書く。"""
    raw = bytearray()
    for y in range(height):
        raw.append(0)  # filter type: None
        row = pixels[y]
        for px in row:
            raw += bytes(px)

    def chunk(tag: bytes, data: bytes) -> bytes:
        return (
            struct.pack(">I", len(data))
            + tag
            + data
            + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
        )

    header = struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0)
    png = (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", header)
        + chunk(b"IDAT", zlib.compress(bytes(raw), 9))
        + chunk(b"IEND", b"")
    )
    path.write_bytes(png)


def floor_texture(path: Path, size: int, base, accent, seed: int, cell: int) -> None:
    """床タイル。グリッド + 斑（ステージごとに色と粒度を変える）。"""
    rng = Rng(seed)
    table = [rng.uniform(0.0, 1.0) for _ in range(1024)]
    rows = []
    for y in range(size):
        row = []
        for x in range(size):
            # グリッド線
            gx = min(x % cell, cell - 1 - (x % cell))
            gy = min(y % cell, cell - 1 - (y % cell))
            edge = 1.0 if min(gx, gy) < 2 else 0.0
            # 斑（セルごとの明度差）
            key = ((x // cell) * 73856093) ^ ((y // cell) * 19349663)
            patch = table[key % len(table)] * 0.35
            # 細かいざらつき
            grain = table[((x * 31 + y * 17) ^ seed) % len(table)] * 0.12
            t = patch + grain
            r = base[0] * (1 - t) + accent[0] * t
            g = base[1] * (1 - t) + accent[1] * t
            b = base[2] * (1 - t) + accent[2] * t
            if edge:
                r = min(255, r * 0.45 + accent[0] * 0.5)
                g = min(255, g * 0.45 + accent[1] * 0.5)
                b = min(255, b * 0.45 + accent[2] * 0.5)
            row.append((int(r), int(g), int(b), 255))
        rows.append(row)
    write_png(path, size, size, rows)


def build_images(out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    # 床は「影が乗る面」でもあるので、暗く作ると落ちた影と見分けが付かなくなる。
    # ベースを中間調まで上げ、アクセントとの差でタイルを見せる。
    floor_texture(out / "floor_hull.png", 256, (86, 116, 128), (152, 204, 212), seed=11, cell=32)
    floor_texture(out / "floor_reactor.png", 256, (118, 84, 62), (214, 152, 96), seed=23, cell=24)
    floor_texture(out / "floor_vent.png", 256, (86, 78, 118), (176, 156, 232), seed=37, cell=40)


# --- WAV -------------------------------------------------------------------


def write_wav(path: Path, samples) -> None:
    with wave.open(str(path), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SAMPLE_RATE)
        frames = bytearray()
        for s in samples:
            v = int(max(-1.0, min(1.0, s)) * 32000)
            frames += struct.pack("<h", v)
        w.writeframes(bytes(frames))


def ambience(path: Path, seconds: float, partials, noise_level: float, seed: int) -> None:
    """周期が整数回入る正弦波だけで組んだ環境音。継ぎ目なくループする。"""
    total = int(SAMPLE_RATE * seconds)
    rng = Rng(seed)
    table = [rng.uniform(-1.0, 1.0) for _ in range(4096)]
    samples = []
    for i in range(total):
        t = i / SAMPLE_RATE
        v = 0.0
        for cycles, amp in partials:
            freq = cycles / seconds  # seconds 内にちょうど cycles 回
            v += amp * math.sin(2 * math.pi * freq * t)
        # ゆっくりした振幅の揺れ（これもループ長で整数周期）
        v *= 0.75 + 0.25 * math.sin(2 * math.pi * (2 / seconds) * t)
        v += noise_level * table[(i * 7919) % len(table)]
        samples.append(v * 0.5)
    write_wav(path, samples)


def chirp(path: Path, seconds: float, f0: float, f1: float, decay: float, noise: float, seed: int) -> None:
    total = int(SAMPLE_RATE * seconds)
    rng = Rng(seed)
    table = [rng.uniform(-1.0, 1.0) for _ in range(2048)]
    samples = []
    phase = 0.0
    for i in range(total):
        t = i / total
        freq = f0 + (f1 - f0) * t
        phase += 2 * math.pi * freq / SAMPLE_RATE
        env = math.exp(-decay * t) * min(1.0, i / 64)
        v = math.sin(phase) * env
        v += noise * table[(i * 7919) % len(table)] * env
        samples.append(v * 0.7)
    write_wav(path, samples)


def build_sounds(out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    # ステージ固有の環境音（8 秒ループ）
    ambience(out / "amb_hull.wav", 8.0, [(440, 0.5), (661, 0.25), (880, 0.14)], 0.05, seed=5)
    ambience(out / "amb_reactor.wav", 8.0, [(360, 0.45), (720, 0.3), (1081, 0.18)], 0.09, seed=6)
    ambience(out / "amb_vent.wav", 8.0, [(520, 0.4), (779, 0.3), (1560, 0.12)], 0.14, seed=7)
    # 全ステージ共有の SE
    chirp(out / "se_pickup.wav", 0.28, 620, 1560, 5.0, 0.02, seed=8)
    chirp(out / "se_hit.wav", 0.34, 220, 70, 4.0, 0.35, seed=9)


