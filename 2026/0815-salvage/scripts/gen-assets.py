def build_video(out: Path) -> None:
    """背景ループ動画（stage1 のみ）。ffmpeg が無ければスキップして警告する。"""
    out.mkdir(parents=True, exist_ok=True)
    target = out / "backdrop_hull.mp4"
    if shutil.which("ffmpeg") is None:
        print("warning: ffmpeg not found — skipping backdrop_hull.mp4", file=sys.stderr)
        return
    graph = (
        "gradients=s=480x270:c0=0x04121c:c1=0x1d6b7d:c2=0x3ba8b8:c3=0x071d28"
        ":nb_colors=4:speed=0.02:x0=20:y0=30:x1=460:y1=240:d=8:r=20,"
        "geq=r='r(X,Y)*(0.55+0.45*sin((X+Y)/26+T*1.6))'"
        ":g='g(X,Y)*(0.55+0.45*sin((X+Y)/26+T*1.6))'"
        ":b='b(X,Y)*(0.6+0.4*sin((X+Y)/26+T*1.6))',"
        "vignette=PI/5,format=yuv420p"
    )
    cmd = [
        "ffmpeg", "-y", "-hide_banner", "-loglevel", "error",
        "-f", "lavfi", "-i", graph,
        "-t", "8", "-c:v", "h264_videotoolbox", "-b:v", "500k",
        str(target),
    ]
    result = subprocess.run(cmd, capture_output=True, text=True)
    if result.returncode != 0:
        print(f"warning: ffmpeg failed:\n{result.stderr}", file=sys.stderr)


def main() -> None:
    build_models(RES / "Models")
    build_images(RES / "Images")
    build_sounds(RES / "Sounds")
    build_video(RES / "Videos")
    for p in sorted(RES.rglob("*")):
        if p.is_file():
            print(f"{p.relative_to(RES)}  {p.stat().st_size / 1024:.1f} KB")


if __name__ == "__main__":
    main()
